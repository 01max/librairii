use crate::{Result, cargo, check_tool, command, host, output, root};
use serde_json::json;
use std::{env, fs, process::Command};
fn context(lane: &str) -> Result {
    let hardware = env::var("LIBRAIRII_BENCH_HARDWARE").unwrap_or_else(|_| {
        "unidentified hardware; diagnostic only, no product budget comparison".into()
    });
    fs::create_dir_all(root().join("target/quality"))?;
    fs::write(
        root().join(format!("target/quality/{lane}-context.json")),
        serde_json::to_vec_pretty(&json!({
            "source_commit":output("git", &["rev-parse", "HEAD"] )?.trim(),
            "rustc":output("rustc", &["-vV"] )?, "os":env::consts::OS, "arch":env::consts::ARCH,
            "hardware":hardware, "parallelism":std::thread::available_parallelism()?.get(),
            "fixtures":"synthetic fixed identity strings, generated byte arrays and owned temporary files",
            "scope":"foundation infrastructure only; no domain/custody/upgrade or UI budget claim"
        }))?,
    )?;
    Ok(())
}
pub fn coverage() -> Result {
    host()?;
    check_tool("cargo-llvm-cov")?;
    check_tool("cargo-nextest")?;
    context("coverage")?;
    command(
        &cargo(),
        &[
            "llvm-cov",
            "nextest",
            "--workspace",
            "--locked",
            "--profile",
            "ci",
            "--lcov",
            "--output-path",
            "target/quality/lcov.info",
        ],
    )?;
    command(
        &cargo(),
        &[
            "llvm-cov",
            "report",
            "--html",
            "--output-dir",
            "target/quality/coverage",
        ],
    )
}
pub fn bench(smoke: bool) -> Result {
    host()?;
    context("bench")?;
    let mut args = vec![
        "bench",
        "--locked",
        "-p",
        "librairii-core",
        "--bench",
        "identities",
    ];
    if smoke {
        args.extend(["--", "--test"]);
    }
    command(&cargo(), &args)
}
pub fn fuzz() -> Result {
    check_tool("cargo-fuzz")?;
    context("fuzz")?;
    let config: toml::Value = toml::from_str(&fs::read_to_string(
        root().join("fuzz/rust-toolchain.toml"),
    )?)?;
    let pin = config["toolchain"]["channel"]
        .as_str()
        .ok_or("missing exact fuzz toolchain")?;
    if !pin.starts_with("nightly-") || pin.len() != 18 {
        return Err("fuzz toolchain must be exact dated nightly".into());
    }
    let working = root().join("target/quality/fuzz");
    let corpus = working.join("corpus");
    let artifacts = working.join("artifacts");
    fs::create_dir_all(&corpus)?;
    fs::create_dir_all(&artifacts)?;
    for entry in fs::read_dir(root().join("fuzz/corpus/identity"))? {
        let entry = entry?;
        if entry.file_type()?.is_file() {
            fs::copy(entry.path(), corpus.join(entry.file_name()))?;
        }
    }
    // cargo-fuzz has no locked flag: resolve with Cargo locked, run offline,
    // and reject any lockfile mutation before reporting success.
    let lock_path = root().join("fuzz/Cargo.lock");
    let locked = fs::read(&lock_path)?;
    let status = Command::new("rustup")
        .args([
            "run",
            pin,
            "cargo",
            "metadata",
            "--locked",
            "--format-version",
            "1",
        ])
        .current_dir(root().join("fuzz"))
        .stdout(std::process::Stdio::null())
        .status()?;
    if !status.success() {
        return Err("locked fuzz graph validation failed".into());
    }
    let status = Command::new("rustup")
        .args(["run", pin, "cargo", "fuzz", "run", "identity"])
        .arg(&corpus)
        .args([
            "--",
            "-max_total_time=30",
            "-max_len=128",
            "-timeout=2",
            "-rss_limit_mb=512",
            "-seed=1",
        ])
        .arg(format!("-artifact_prefix={}/", artifacts.display()))
        .env("CARGO_NET_OFFLINE", "true")
        .env("CARGO_TARGET_DIR", root().join("fuzz/target"))
        .current_dir(root().join("fuzz"))
        .status()?;
    if fs::read(&lock_path)? != locked {
        return Err("fuzz run changed the committed lockfile".into());
    }
    if !status.success() {
        return Err("bounded identity fuzz run failed".into());
    }
    Ok(())
}
